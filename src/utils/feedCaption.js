import { normalizeBannerLink } from './bannerLink.js'

function escapeHtml(raw) {
  return String(raw ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

function decodeHtmlEntities(raw) {
  return String(raw ?? '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&#39;/g, "'")
    .replace(/&quot;/gi, '"')
    .replace(/&gt;/gi, '>')
    .replace(/&lt;/gi, '<')
    .replace(/&amp;/gi, '&')
}

export function sanitizeFeedCaptionHtml(raw) {
  const input = String(raw ?? '').trim()
  if (!input) return ''

  // Legacy plain-text caption -> preserve line breaks safely
  if (!/<(?:a|br|div|p|strong|b|em|i)\b/i.test(input)) {
    return escapeHtml(input).replace(/\r?\n/g, '<br>')
  }

  // Normalize block wrappers generated by contenteditable into <br>
  const preNormalized = input
    .replace(/\r\n/g, '\n')
    .replace(/<\/(?:div|p)\s*>\s*<(?:div|p)(?:\s[^>]*)?>/gi, '<br>')
    .replace(/<(?:div|p)(?:\s[^>]*)?>/gi, '<br>')
    .replace(/<\/(?:div|p)\s*>/gi, '')

  const tokenRegex = /<(\/?)([a-zA-Z0-9]+)([^>]*)>|([^<]+)/g
  let out = ''
  const linkStack = []
  let strongDepth = 0
  let emDepth = 0
  let match

  while ((match = tokenRegex.exec(preNormalized)) !== null) {
    const [, closingSlash, rawTagName, rawAttrs, textChunk] = match

    if (textChunk !== undefined) {
      const decoded = decodeHtmlEntities(textChunk)
      out += escapeHtml(decoded).replace(/\n/g, '<br>')
      continue
    }

    const tag = String(rawTagName || '').toLowerCase()
    const isClose = closingSlash === '/'

    if (tag === 'br' && !isClose) {
      out += '<br>'
      continue
    }

    if (tag === 'strong' || tag === 'b') {
      if (!isClose) {
        strongDepth += 1
        out += '<strong>'
      } else if (strongDepth > 0) {
        strongDepth -= 1
        out += '</strong>'
      }
      continue
    }

    if (tag === 'em' || tag === 'i') {
      if (!isClose) {
        emDepth += 1
        out += '<em>'
      } else if (emDepth > 0) {
        emDepth -= 1
        out += '</em>'
      }
      continue
    }

    if (tag === 'a') {
      if (!isClose) {
        const hrefMatch = String(rawAttrs || '').match(/\bhref\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i)
        const rawHref = decodeHtmlEntities(hrefMatch?.[1] || hrefMatch?.[2] || hrefMatch?.[3] || '').trim()
        const validHref = normalizeBannerLink(rawHref)
        if (validHref) {
          linkStack.push(true)
          out += `<a href="${escapeHtml(validHref)}" target="_blank" rel="noopener noreferrer">`
        } else {
          linkStack.push(false)
        }
      } else if (linkStack.length > 0) {
        const wasValid = linkStack.pop()
        if (wasValid) {
          out += '</a>'
        }
      }
    }
  }

  while (linkStack.length > 0) {
    if (linkStack.pop()) out += '</a>'
  }
  while (emDepth > 0) {
    emDepth -= 1
    out += '</em>'
  }
  while (strongDepth > 0) {
    strongDepth -= 1
    out += '</strong>'
  }

  return out
    .replace(/^(?:<br>\s*)+/i, '')
    .replace(/(?:\s*<br>)+$/i, '')
    .replace(/(?:<br>\s*){3,}/gi, '<br><br>')
    .trim()
}

export function stripFeedCaptionToPlainText(raw) {
  const input = String(raw ?? '')
  if (!input) return ''
  return decodeHtmlEntities(
    input
      .replace(/<br\s*\/?>/gi, '\n')
      .replace(/<\/(?:p|div)\s*>/gi, '\n')
      .replace(/<[^>]+>/g, ''),
  )
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

export function compareFeedPosts(a = {}, b = {}) {
  const pinA = a?.Pinned ? 1 : 0
  const pinB = b?.Pinned ? 1 : 0
  if (pinA !== pinB) return pinB - pinA

  const orderA = Number(a?.Sort_order || 0)
  const orderB = Number(b?.Sort_order || 0)
  if (orderA > 0 && orderB > 0 && orderA !== orderB) {
    return orderA - orderB
  }
  if (orderA > 0 && orderB <= 0) return -1
  if (orderB > 0 && orderA <= 0) return 1

  return Number(b?.Created_at || 0) - Number(a?.Created_at || 0)
}
