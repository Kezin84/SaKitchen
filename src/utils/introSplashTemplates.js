function clampHexByte(v) {
  return Math.max(0, Math.min(255, Math.round(v)))
}

function mixDarkHex(hex, ratio) {
  const clean = /^#[0-9a-fA-F]{6}$/.test(String(hex || '')) ? String(hex).slice(1) : '059669'
  const r = parseInt(clean.slice(0, 2), 16)
  const g = parseInt(clean.slice(2, 4), 16)
  const b = parseInt(clean.slice(4, 6), 16)
  const nr = clampHexByte(r * (1 - ratio))
  const ng = clampHexByte(g * (1 - ratio))
  const nb = clampHexByte(b * (1 - ratio))
  return `#${nr.toString(16).padStart(2, '0')}${ng.toString(16).padStart(2, '0')}${nb.toString(16).padStart(2, '0')}`
}

