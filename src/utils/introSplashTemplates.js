export function resolveIntroSplashPalette(bgId = 'wok-crimson', primaryColor = '#059669', secondaryColor = '#facc15') {
  const found = INTRO_BG_TEMPLATES.find((b) => b.id === bgId)
  if (!found || found.isAuto) {
    const center = mixDarkHex(primaryColor, 0.25)
    const mid = mixDarkHex(primaryColor, 0.56)
    const deep = mixDarkHex(primaryColor, 0.82)
    const edge = mixDarkHex(primaryColor, 0.92)
    const accent = /^#[0-9a-fA-F]{6}$/.test(String(secondaryColor || '')) ? secondaryColor : '#facc15'
    return {
      center,
      mid,
      deep,
      edge,
      accent,
      glow: primaryColor || '#10b981',
      titleStart: '#fffbeb',
      titleMid: accent,
      titleEnd: primaryColor || '#34d399',
      loaderBg: `radial-gradient(circle at 50% 45%, ${mid} 0%, ${deep} 65%, ${edge} 100%)`,
    }
  }

  return {
    center: found.center,
    mid: found.mid,
    deep: found.deep,
    edge: found.edge,
    accent: found.accent,
    glow: found.glow,
    titleStart: found.titleStart,
    titleMid: found.titleMid,
    titleEnd: found.titleEnd,
    loaderBg: `radial-gradient(circle at 50% 45%, ${found.mid} 0%, ${found.deep} 65%, ${found.edge} 100%)`,
  }
}
